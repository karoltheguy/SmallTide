"""Generates crates/smalltide-io/src/unicode_cats.rs: general-category classes needed by the
o200k-style pre-tokenizer regex (\\p{Lu} \\p{Lt} \\p{Lm} \\p{Lo} \\p{Ll} \\p{M} \\p{N}).

    python -I tools/gen_unicode_cats.py crates/smalltide-io/src/unicode_cats.rs
"""

import sys
import unicodedata

CLS = {"Lu": 1, "Ll": 2, "Lt": 3, "Lm": 4, "Lo": 5, "Mn": 6, "Mc": 6, "Me": 6, "Nd": 7, "Nl": 7, "No": 7}


def main():
    out = sys.argv[1]
    ranges = []
    cur = None
    for cp in range(0x110000):
        c = CLS.get(unicodedata.category(chr(cp)), 0)
        if cur and cur[2] == c and cur[1] == cp - 1:
            cur[1] = cp
        else:
            if cur and cur[2] != 0:
                ranges.append(tuple(cur))
            cur = [cp, cp, c]
    if cur and cur[2] != 0:
        ranges.append(tuple(cur))
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("//! Generated by tools/gen_unicode_cats.py from Python unicodedata "
                f"(Unicode {unicodedata.unidata_version}). Do not edit.\n\n")
        f.write("/// 0 other, 1 Lu, 2 Ll, 3 Lt, 4 Lm, 5 Lo, 6 M (Mn/Mc/Me), 7 N (Nd/Nl/No).\n")
        f.write(f"pub static RANGES: [(u32, u32, u8); {len(ranges)}] = [\n")
        for a, b, c in ranges:
            f.write(f"    (0x{a:X}, 0x{b:X}, {c}),\n")
        f.write("];\n")
    print(f"{len(ranges)} ranges (Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
